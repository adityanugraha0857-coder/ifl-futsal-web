const fs = require("fs");
const path = require("path");

const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, "..", "data");
const usePostgres = Boolean(process.env.DATABASE_URL);
let sqlite;
let pool;

if (usePostgres) {
  const { Pool, types } = require("pg");
  types.setTypeParser(20, (value) => Number(value));
  pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl:
      process.env.DATABASE_SSL === "false"
        ? false
        : {
            rejectUnauthorized: true,
            ...(process.env.DATABASE_SSL_CA
              ? { ca: process.env.DATABASE_SSL_CA.replace(/\\n/g, "\n") }
              : {}),
          },
    max: 10,
    connectionTimeoutMillis: 10000,
    idleTimeoutMillis: 30000,
  });
} else {
  if (process.env.NODE_ENV === "production") {
    throw new Error("DATABASE_URL wajib diisi saat NODE_ENV=production.");
  }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const Database = require("better-sqlite3");
  sqlite = new Database(path.join(DATA_DIR, "ifl-events.sqlite"));
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
}

function postgresPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

const db = {
  async all(sql, params = []) {
    if (usePostgres) {
      const result = await pool.query(postgresPlaceholders(sql), params);
      return result.rows;
    }
    return sqlite.prepare(sql).all(...params);
  },

  async get(sql, params = []) {
    if (usePostgres) {
      const result = await pool.query(postgresPlaceholders(sql), params);
      return result.rows[0];
    }
    return sqlite.prepare(sql).get(...params);
  },

  async run(sql, params = []) {
    if (usePostgres) {
      const result = await pool.query(postgresPlaceholders(sql), params);
      return {
        changes: result.rowCount,
        id: result.rows[0]?.id,
        rows: result.rows,
      };
    }
    if (/^\s*(INSERT|UPDATE|DELETE)\b/i.test(sql) && /\bRETURNING\b/i.test(sql)) {
      const row = sqlite.prepare(sql).get(...params);
      return { changes: row ? 1 : 0, id: row?.id, rows: row ? [row] : [] };
    }
    const result = sqlite.prepare(sql).run(...params);
    return { changes: result.changes, id: result.lastInsertRowid, rows: [] };
  },

  async transaction(callback) {
    if (usePostgres) {
      const client = await pool.connect();
      const tx = {
        run: async (sql, params = []) => {
          const result = await client.query(postgresPlaceholders(sql), params);
          return {
            changes: result.rowCount,
            id: result.rows[0]?.id,
            rows: result.rows,
          };
        },
      };
      try {
        await client.query("BEGIN");
        const result = await callback(tx);
        await client.query("COMMIT");
        return result;
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    }

    sqlite.exec("BEGIN");
    try {
      const result = await callback({
        run: async (sql, params = []) => {
          const info = sqlite.prepare(sql).run(...params);
          return { changes: info.changes, id: info.lastInsertRowid, rows: [] };
        },
      });
      sqlite.exec("COMMIT");
      return result;
    } catch (error) {
      sqlite.exec("ROLLBACK");
      throw error;
    }
  },
};

async function initDatabase() {
  if (usePostgres) {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS admins (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE TABLE IF NOT EXISTS events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        category TEXT NOT NULL DEFAULT 'Turnamen',
        location TEXT NOT NULL DEFAULT 'Pontianak',
        start_date DATE NOT NULL,
        end_date DATE,
        status TEXT NOT NULL DEFAULT 'Akan Datang',
        description TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE TABLE IF NOT EXISTS matches (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        event_id BIGINT REFERENCES events(id) ON DELETE SET NULL,
        match_date DATE NOT NULL,
        match_time TEXT NOT NULL DEFAULT '',
        home_team TEXT NOT NULL,
        away_team TEXT NOT NULL,
        home_score INTEGER,
        away_score INTEGER,
        venue TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Terjadwal',
        round_name TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE TABLE IF NOT EXISTS settings (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS sessions (
        sid VARCHAR NOT NULL PRIMARY KEY,
        sess JSON NOT NULL,
        expire TIMESTAMP(6) NOT NULL
      );
      CREATE INDEX IF NOT EXISTS sessions_expire_idx ON sessions(expire);
    `);
    return;
  }

  sqlite.exec(`
    CREATE TABLE IF NOT EXISTS admins (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      username TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS events (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'Turnamen',
      location TEXT NOT NULL DEFAULT 'Pontianak',
      start_date TEXT NOT NULL,
      end_date TEXT,
      status TEXT NOT NULL DEFAULT 'Akan Datang',
      description TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS matches (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      event_id INTEGER,
      match_date TEXT NOT NULL,
      match_time TEXT NOT NULL DEFAULT '',
      home_team TEXT NOT NULL,
      away_team TEXT NOT NULL,
      home_score INTEGER,
      away_score INTEGER,
      venue TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'Terjadwal',
      round_name TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE SET NULL
    );
    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
  `);
}

function createSessionStore(session) {
  if (usePostgres) {
    const PostgreSQLStore = require("connect-pg-simple")(session);
    return new PostgreSQLStore({
      pool,
      tableName: "sessions",
      createTableIfMissing: false,
    });
  }
  return new session.MemoryStore();
}

async function closeDatabase() {
  if (usePostgres) await pool.end();
  else sqlite.close();
}

module.exports = {
  closeDatabase,
  createSessionStore,
  db,
  initDatabase,
};
